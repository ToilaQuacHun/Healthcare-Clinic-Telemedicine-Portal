USE Phrase3;
SELECT 'USER_ACCOUNT' AS TableName,COUNT(*) AS RowsCount FROM USER_ACCOUNT
UNION ALL SELECT 'PATIENT',COUNT(*) FROM PATIENT
UNION ALL SELECT 'DOCTOR',COUNT(*) FROM DOCTOR
UNION ALL SELECT 'DOCTOR_SCHEDULE',COUNT(*) FROM DOCTOR_SCHEDULE
UNION ALL SELECT 'APPOINTMENT',COUNT(*) FROM APPOINTMENT
UNION ALL SELECT 'CONSULTATION_SESSION',COUNT(*) FROM CONSULTATION_SESSION
UNION ALL SELECT 'PRESCRIPTION',COUNT(*) FROM PRESCRIPTION
UNION ALL SELECT 'PRESCRIPTION_ITEM',COUNT(*) FROM PRESCRIPTION_ITEM;
SELECT TRIGGER_NAME,ACTION_TIMING,EVENT_MANIPULATION FROM INFORMATION_SCHEMA.TRIGGERS WHERE TRIGGER_SCHEMA=DATABASE();
SELECT TABLE_NAME FROM INFORMATION_SCHEMA.VIEWS WHERE TABLE_SCHEMA=DATABASE();
SELECT COUNT(*) AS LinkedDoctors FROM DOCTOR WHERE UserID IS NOT NULL;
SELECT COUNT(*) AS LinkedPatients FROM PATIENT WHERE UserID IS NOT NULL;
SELECT COUNT(*) AS ActiveDoctors FROM DOCTOR WHERE IsActive=1;
